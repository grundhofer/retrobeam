const read = (p) => readFileSync(p, "utf8");

// The SVG as a page inlines it: XML prolog, doctype and leading comments dropped (tools/inline_assets.py clean()).
function cleanSvg(text) {
  return text.replace(/^\s*(<\?xml[^>]*\?>\s*)?(<!DOCTYPE[^>]*>\s*)?((<!--[\s\S]*?-->)\s*)*/, "").trim();
}

function tileOf(L, id, where) {
  const file = path.join(L.inline, `tile-${id}.svg`);
  if (!existsSync(file)) {
    throw new UsageError(`${where}: no brand/inline/tile-${id}.svg in this export (export with --product ${id}, or ` +
                         `--product ${UMBRELLA} for every tile)`);
  }
  const svg = cleanSvg(read(file));
  const name = /aria-label="([^"]+)"/.exec(svg);
  if (!name) throw new UsageError(`brand/inline/tile-${id}.svg has no aria-label (the product name)`);
  return { svg, name: unescapeAttr(name[1]) };
}

function chevron(L) {
  const m = /<symbol id="chevron-right" ([^>]*)>([\s\S]*?)<\/symbol>/.exec(read(L.sprite));
  if (!m) throw new UsageError("icons sprite has no symbol chevron-right");
  const attrs = m[1].replace(/\bclass="([^"]*)"/, 'class="sb-icon sb-icon--24 $1"');
  return `<svg xmlns="http://www.w3.org/2000/svg" ${attrs} aria-hidden="true" focusable="false">${m[2]}</svg>`;
}

// unicode-range of the upright sebaro Sans faces in fonts.css: the characters the image may use
function coverage(L) {
  const ranges = [];
  for (const block of read(L.fontsCss).match(/@font-face\s*{[^}]*}/g) || []) {
    if (!/font-family:\s*"sebaro Sans"/.test(block) || /font-style:\s*italic/.test(block)) continue;
    const m = /unicode-range:\s*([^;]+);/.exec(block);
    if (!m) return null;                                      // no range: the face covers what its file has
    for (const part of m[1].split(",")) {
      const [a, b] = part.trim().replace(/^U\+/i, "").split("-");
      ranges.push([parseInt(a, 16), parseInt(b ?? a, 16)]);
    }
  }
  if (!ranges.length) throw new UsageError("fonts.css declares no upright sebaro Sans face");
  return ranges;
}

// ------------------------------------------------------------------------- the page list, checked by the schema itself
const KEYWORDS = new Set(["$schema", "$id", "$comment", "$defs", "title", "description", "default", "type", "required",
  "properties", "additionalProperties", "enum", "pattern", "minLength", "maxLength", "minimum", "maximum", "items",
  "minItems", "maxItems", "uniqueItems", "$ref"]);
const TYPES = { object: (v) => v !== null && typeof v === "object" && !Array.isArray(v), array: Array.isArray,
  string: (v) => typeof v === "string", integer: Number.isInteger, boolean: (v) => typeof v === "boolean" };

export function validate(root, schema, value, at = "$", errors = []) {
  if (schema.$ref) {
    const m = /^#\/\$defs\/([A-Za-z0-9_-]+)$/.exec(schema.$ref);
    if (!m || !root.$defs?.[m[1]]) throw new Error(`pages.schema.json: unsupported $ref ${schema.$ref}`);
    validate(root, root.$defs[m[1]], value, at, errors);
  }
  for (const k of Object.keys(schema)) if (!KEYWORDS.has(k)) throw new Error(`pages.schema.json: keyword ${k} is not read`);
  if (schema.type && !TYPES[schema.type](value)) { errors.push(`${at}: expected ${schema.type}`); return errors; }
  if (schema.enum && !schema.enum.includes(value)) errors.push(`${at}: ${JSON.stringify(value)} is not one of ${schema.enum.join(", ")}`);
  if (typeof value === "string") {
    const n = [...value].length;
    if (schema.minLength !== undefined && n < schema.minLength) errors.push(`${at}: shorter than ${schema.minLength}`);
    if (schema.maxLength !== undefined && n > schema.maxLength) errors.push(`${at}: longer than ${schema.maxLength} characters`);
    if (schema.pattern && !new RegExp(schema.pattern, "u").test(value)) errors.push(`${at}: ${JSON.stringify(value)} does not match ${schema.pattern}`);
  }
  if (typeof value === "number") {
    if (schema.minimum !== undefined && value < schema.minimum) errors.push(`${at}: below ${schema.minimum}`);
    if (schema.maximum !== undefined && value > schema.maximum) errors.push(`${at}: above ${schema.maximum}`);
  }
  if (Array.isArray(value)) {
    if (schema.minItems !== undefined && value.length < schema.minItems) errors.push(`${at}: fewer than ${schema.minItems} items`);
    if (schema.maxItems !== undefined && value.length > schema.maxItems) errors.push(`${at}: more than ${schema.maxItems} items`);
    if (schema.uniqueItems && new Set(value.map((v) => JSON.stringify(v))).size !== value.length) errors.push(`${at}: items repeat`);
    if (schema.items) value.forEach((v, i) => validate(root, schema.items, v, `${at}[${i}]`, errors));
  }
  if (TYPES.object(value)) {
    for (const k of schema.required || []) if (!(k in value)) errors.push(`${at}: ${k} is missing`);
    for (const [k, v] of Object.entries(value)) {
      if (schema.properties?.[k]) validate(root, schema.properties[k], v, `${at}.${k}`, errors);
      else if (schema.additionalProperties === false) errors.push(`${at}: unknown key ${k}`);
    }
  }
  return errors;
}

function loadPages(L, file) {
  let doc;
  try { doc = JSON.parse(read(file)); } catch (e) { throw new UsageError(`${file}: ${e.message}`); }
  const schema = JSON.parse(read(L.schema));
  const errors = validate(schema, schema, doc);
  const ids = new Set(), outs = new Set();
  for (const [i, p] of (Array.isArray(doc?.pages) ? doc.pages : []).entries()) {
    if (p?.id && ids.has(p.id)) errors.push(`$.pages[${i}]: id ${p.id} repeats`);
    const out = p?.output ?? p?.id;
    if (out && outs.has(out)) errors.push(`$.pages[${i}]: output ${out} repeats`);
    ids.add(p?.id); outs.add(out);
    if (typeof p?.date === "string" && /^\d{4}-\d{2}-\d{2}$/.test(p.date)
        && new Date(`${p.date}T00:00:00Z`).toISOString().slice(0, 10) !== p.date) {
      errors.push(`$.pages[${i}].date: ${p.date} is not a calendar date`);
    }
  }
  if (errors.length) throw new UsageError(`${file} does not match pages.schema.json:\n  ` + errors.join("\n  "));
  return doc;
}

// ------------------------------------------------------------------------- the template (a small mustache subset)
// {{name}} escaped, {{{name}}} raw, {{#name}}…{{/name}} once if truthy or once per array item, {{^name}}…{{/name}} if
// falsy; dotted names (crumb.length); a section tag alone on its line takes the line with it.
function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
}
function unescapeAttr(s) {
  return s.replace(/&(amp|lt|gt|quot|#39);/g, (_, e) => ({ amp: "&", lt: "<", gt: ">", quot: '"', "#39": "'" })[e]);
}

function lookup(stack, name) {
  for (let i = stack.length - 1; i >= 0; i--) {
    let v = stack[i];
    const parts = name.split(".");
    if (v === null || typeof v !== "object" || !(parts[0] in v)) continue;
    for (const p of parts) v = v == null ? undefined : v[p];
    return v;
  }
  return undefined;
}

export function fill(template, view) {
  const src = template.replace(/^[ \t]*(\{\{[#^/][^}]+\}\})[ \t]*\r?\n/gm, "$1");
  const tag = /\{\{(\{?)([#^/]?)\s*([\w.]+)\s*\}?\}\}/g;
  function run(from, stack, until, skip = false) {      // skip: find the end of a section without evaluating it
    let out = "", pos = from, m;
    tag.lastIndex = from;
    while ((m = tag.exec(src))) {
      out += src.slice(pos, m.index);
      const [whole, raw, kind, name] = m;
      pos = m.index + whole.length;
      if (kind === "/") {
        if (name !== until) throw new Error(`template: {{/${name}}} closes {{#${until}}}`);
        return { out, end: pos };
      }
      if ((kind === "#" || kind === "^") && skip) {
        pos = run(pos, stack, name, true).end; tag.lastIndex = pos;
        continue;
      }
      if (kind === "#" || kind === "^") {
        const v = lookup(stack, name);
        const items = kind === "^" ? ((!v || (Array.isArray(v) && !v.length)) ? [null] : [])
          : Array.isArray(v) ? v : v ? [v] : [];
        let end = null;
        for (const item of items) {
          const r = run(pos, item === null || typeof item !== "object" ? stack : [...stack, item], name);
          out += r.out; end = r.end;
        }
        if (end === null) end = run(pos, stack, name, true).end;
        pos = end; tag.lastIndex = end;
        continue;
      }
      if (skip) continue;
      const v = lookup(stack, name);
      if (v === undefined) throw new Error(`template: {{${name}}} has no value`);
      out += raw ? String(v) : escapeHtml(v);
    }
    if (until) throw new Error(`template: {{#${until}}} is not closed`);
    return { out: out + src.slice(pos), end: src.length };
  }
  return run(0, [view], null).out;
}

// ------------------------------------------------------------------------- one page
// The host as people read it (OR-14): URL.host is the ASCII (punycode) form, so an umlaut host would be drawn as
// „xn--…“; domainToUnicode gives it back as written, the port stays. A host it cannot read stays as URL gives it.
export function shownHost(origin) {
  const u = new URL(origin);
  const host = domainToUnicode(u.hostname) || u.hostname;
  return u.port ? `${host}:${u.port}` : host;
}

function href(fromDir, file) {     // both real paths, so a symbolic link (macOS /var -> /private/var) adds no detour
  return path.relative(realpathSync(fromDir), realpathSync(file)).split(path.sep).map(encodeURIComponent).join("/");
}

export function viewOf(L, doc, page, htmlDir, pagesName) {
  const site = doc.site, lang = site.lang ?? "de", w = WORDS[lang];
  const product = page.product ?? site.product;
  const where = `page ${page.id}`;
  const own = tileOf(L, product, where);
  const apps = (page.apps ?? []).map((id) => { const t = tileOf(L, id, where); return { tile: t.svg, name: t.name }; });
  const meta = [];
  if (page.readingMinutes) meta.push(w.minutes(page.readingMinutes));
  if (page.date) meta.push(`${w[page.dateKind ?? "updated"]} ${w.date(page.date)}`);
  meta.push(shownHost(site.origin));
  const crumb = (page.path ?? []).map((text, i) => ({ text, sep: i > 0 }));
  const umbrella = product === UMBRELLA;
  return {
    lang, umbrella, title: page.title, productName: own.name, tile: own.svg, apps, crumb,
    meta: meta.join(" · "),
    variant: crumb.length || page.readingMinutes || page.date ? "page" : "start",
    docTitle: `${own.name} · ${page.title}`,
    generatedNote: `${MARK} ${VERSION} from brand/og/template.html and ${pagesName}, page ${page.id}; do not edit`,
    fontsCss: href(htmlDir, L.fontsCss), tokensCss: href(htmlDir, L.tokensCss), spriteCss: href(htmlDir, L.spriteCss),
    chevron: chevron(L),
    lockupLarge: cleanSvg(read(L.lockupLarge)),
    lockupSmall: cleanSvg(read(L.lockupSmall)),
  };
}

function textsOf(view) {
  return [["title", view.title], ["product name", view.productName], ["meta", view.meta],
          ...view.crumb.map((c) => ["path", c.text]), ...view.apps.map((a) => ["app name", a.name])];
}

function uncovered(ranges, view) {
  if (!ranges) return [];
  const bad = [];
  for (const [what, text] of textsOf(view)) {
    for (const ch of new Set([...text])) {
      const cp = ch.codePointAt(0);
      if (!ranges.some(([a, b]) => cp >= a && cp <= b)) bad.push(`${what}: U+${cp.toString(16).toUpperCase().padStart(4, "0")}`);
    }
  }
  return bad;
}

export function headOf(doc, page, productName, appNames) {
  const site = doc.site, w = WORDS[site.lang ?? "de"];
  const base = site.imageBase ?? "/og/";
  // through URL, so a path such as /phase-2/übung/ is percent-encoded (origin and url are checked by the schema)
  const image = new URL(`${site.origin}${base}${page.output ?? page.id}.png`).href;
  const url = new URL(`${site.origin}${page.url}`).href;
  const alt = page.alt ?? `${productName}: ${page.title}` + (appNames.length ? ` ${w.apps(appNames)}` : "");
  const tags = [{ tag: "link", rel: "canonical", href: url }];
  if (page.description) tags.push({ tag: "meta", name: "description", content: page.description });
  for (const [property, content] of [["og:type", page.type ?? "article"], ["og:site_name", site.name],
    ["og:locale", w.locale], ["og:url", url], ["og:title", page.title],
    ...(page.description ? [["og:description", page.description]] : []), ["og:image", image],
    ["og:image:width", String(SIZE.width)], ["og:image:height", String(SIZE.height)], ["og:image:alt", alt]]) {
    tags.push({ tag: "meta", property, content });
  }
  tags.push({ tag: "meta", name: "twitter:card", content: "summary_large_image" });
  const html = tags.map(({ tag, ...a }) => `<${tag} ${Object.entries(a).map(([k, v]) => `${k}="${escapeHtml(v)}"`).join(" ")}>`);
  return { id: page.id, image, alt, tags, html: `<!-- ${MARK} ${VERSION}; do not edit -->\n${html.join("\n")}\n` };
}

// ------------------------------------------------------------------------- PNG (8-bit RGB / RGBA, not interlaced)
const CRC = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
function crc32(buf) { let c = 0xFFFFFFFF; for (const b of buf) c = CRC[(c ^ b) & 0xFF] ^ (c >>> 8); return (c ^ 0xFFFFFFFF) >>> 0; }

export function decodePng(buf) {
  if (buf.readUInt32BE(0) !== 0x89504E47) throw new Error("not a PNG");
  let pos = 8, ihdr = null; const idat = [];
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos), type = buf.toString("latin1", pos + 4, pos + 8), data = buf.subarray(pos + 8, pos + 8 + len);
    if (type === "IHDR") ihdr = { width: data.readUInt32BE(0), height: data.readUInt32BE(4), depth: data[8], colorType: data[9], interlace: data[12] };
    else if (type === "IDAT") idat.push(data);
    else if (type === "IEND") break;
    pos += 12 + len;
  }
  if (!ihdr || ihdr.depth !== 8 || ![2, 6].includes(ihdr.colorType) || ihdr.interlace) {
    throw new Error(`unsupported PNG ${JSON.stringify(ihdr)}`);
  }
  const bpp = ihdr.colorType === 6 ? 4 : 3, stride = ihdr.width * bpp, raw = zlib.inflateSync(Buffer.concat(idat));
  const px = Buffer.alloc(stride * ihdr.height);
  for (let y = 0; y < ihdr.height; y++) {
    const f = raw[y * (stride + 1)], line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1)), o = y * stride;
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? px[o + x - bpp] : 0, b = y ? px[o - stride + x] : 0, c = x >= bpp && y ? px[o - stride + x - bpp] : 0;
      let v = line[x];
      if (f === 1) v += a; else if (f === 2) v += b; else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c; }
      px[o + x] = v & 0xFF;
    }
  }
  return { width: ihdr.width, height: ihdr.height, channels: bpp, colorType: ihdr.colorType, data: px };
}

function rgbOf(img) {
  if (img.channels === 3) return { ...img, alphaMin: 255 };
  const out = Buffer.alloc(img.width * img.height * 3);
  let alphaMin = 255;
  for (let i = 0, j = 0; i < img.data.length; i += 4, j += 3) {
    out[j] = img.data[i]; out[j + 1] = img.data[i + 1]; out[j + 2] = img.data[i + 2];
    if (img.data[i + 3] < alphaMin) alphaMin = img.data[i + 3];
  }
  return { width: img.width, height: img.height, channels: 3, colorType: 2, data: out, alphaMin };
}

function chunk(type, data) {
  const head = Buffer.alloc(8); head.writeUInt32BE(data.length, 0); head.write(type, 4, "latin1");
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])), 0);
  return Buffer.concat([head, data, crc]);
}

// 24-bit RGB, filter Sub or Up per row (the smaller sum), zlib level 9, an sRGB chunk and nothing else: deterministic
export function encodePng(img) {
  const stride = img.width * 3, rows = [];
  for (let y = 0; y < img.height; y++) {
    const o = y * stride, sub = Buffer.alloc(stride + 1), up = Buffer.alloc(stride + 1);
    sub[0] = 1; up[0] = 2;
    let sSub = 0, sUp = 0;
    for (let x = 0; x < stride; x++) {
      const v = img.data[o + x];
      sub[x + 1] = (v - (x >= 3 ? img.data[o + x - 3] : 0)) & 0xFF;
      up[x + 1] = (v - (y ? img.data[o - stride + x] : 0)) & 0xFF;
      sSub += sub[x + 1] < 128 ? sub[x + 1] : 256 - sub[x + 1];
      sUp += up[x + 1] < 128 ? up[x + 1] : 256 - up[x + 1];
    }
    rows.push(sUp < sSub ? up : sub);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(img.width, 0); ihdr.writeUInt32BE(img.height, 4); ihdr[8] = 8; ihdr[9] = 2;
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]), chunk("IHDR", ihdr),
    chunk("sRGB", Buffer.from([0])), chunk("IDAT", zlib.deflateSync(Buffer.concat(rows), { level: 9 })), chunk("IEND", Buffer.alloc(0))]);
}

function ground(img) {
  const counts = new Map();
  let best = 0, top = 0;
  for (let i = 0; i < img.data.length; i += 3) {
    const k = (img.data[i] << 16) | (img.data[i + 1] << 8) | img.data[i + 2], n = (counts.get(k) || 0) + 1;
    counts.set(k, n);
    if (n > best) { best = n; top = k; }
  }
  return { rgb: [top >> 16, (top >> 8) & 0xFF, top & 0xFF], share: best / (img.width * img.height) };
}

const hex = (rgb) => "#" + rgb.map((v) => v.toString(16).padStart(2, "0").toUpperCase()).join("");

function parseColour(css) {
  let m = /^#([0-9a-f]{6})$/i.exec(css.trim());
  if (m) return [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16));
  m = /^rgba?\(\s*(\d+)[,\s]+(\d+)[,\s]+(\d+)/i.exec(css.trim());
  return m ? [+m[1], +m[2], +m[3]] : null;
}

// ------------------------------------------------------------------------- in the page (serialized: closes over nothing)
function judgeInPage(maxLines) {
  return document.fonts.ready.then(() => {
    const problems = [], W = 1200, H = 630;
    const q = (s) => document.querySelector(s);
    const wide = (el, what) => {
      if (el && el.scrollWidth > el.clientWidth + 0.5) problems.push(`${what} is wider than its line (${el.scrollWidth} > ${el.clientWidth} px)`);
    };
    const h1 = q(".og-title");
    const lh = parseFloat(getComputedStyle(h1).lineHeight);
    const lines = Math.round(h1.getBoundingClientRect().height / lh);
    if (lines > maxLines) problems.push(`title needs ${lines} lines, ${maxLines} fit (never cut or set smaller: shorten it)`);
    wide(h1, "a word of the title (mark break points with U+00AD)");
    wide(q(".og-crumb"), "path");
    wide(q(".og-product"), "product name");
    wide(q(".og-foot"), "foot (meta, apps and lockup)");
    const el = document.documentElement, foot = q(".og-foot").getBoundingClientRect();
    const padBottom = parseFloat(getComputedStyle(document.body).paddingBottom);
    if (el.scrollWidth > W || el.scrollHeight > H || foot.bottom > H - padBottom + 0.5) {
      problems.push(`content runs past 1200 x 630 (` + (el.scrollWidth > W || el.scrollHeight > H
        ? `${el.scrollWidth} x ${el.scrollHeight} px` : `the foot ends at ${Math.round(foot.bottom)} px, the bottom margin starts at ${H - padBottom} px`) + ")");
    }
    const fonts = [...document.fonts].map((f) => ({ family: f.family.replace(/^["']|["']$/g, ""), style: f.style, weight: f.weight, status: f.status }));
    const bg = getComputedStyle(el).getPropertyValue("--sb-color-bg").trim();
    return { problems, fonts, bg, lines, theme: el.getAttribute("data-theme") };
  });
}

// ------------------------------------------------------------------------- main
function args(argv) {
  const o = { keepHtml: null, head: null, check: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i], next = () => { if (i + 1 >= argv.length) throw new UsageError(`${a} needs a value`); return argv[++i]; };
    if (a === "--pages") o.pages = next();
    else if (a === "--out") o.out = next();
    else if (a === "--head") o.head = next();
    else if (a === "--html-only") o.htmlOnly = next();
    else if (a === "--keep-html") o.keepHtml = next();
    else if (a === "--check") o.check = true;
    else if (a === "--version") o.version = true;
    else throw new UsageError(`unknown argument ${a}`);
  }
  if (o.version) return o;
  if (!o.pages) throw new UsageError("--pages <page list> is required");
  if (!o.htmlOnly === !o.out) throw new UsageError("give either --out <dir> (render) or --html-only <dir>");
  if (o.check && !o.htmlOnly) throw new UsageError("--check works with --html-only");
  return o;
}

function loadPlaywright() {
  for (const base of [path.join(HERE, "render.mjs"), path.join(process.cwd(), "package.json")]) {
    const req = createRequire(base);
    for (const name of ["playwright", "playwright-core", "@playwright/test"]) {
      try {
        const pw = req(name);
        let version = null;
        try { version = req(`${name}/package.json`).version; } catch { /* exports map without package.json */ }
        return { pw, version };
      } catch { /* next */ }
    }
  }
  throw new UsageError("Playwright not found from this file or the working folder: npm install --save-dev playwright, " +
                       "then npx playwright install --only-shell chromium (Chromium only, like the CI, D96 (b))");
}

function htmlOnly(L, doc, o, template) {
  const dir = path.resolve(o.htmlOnly), pagesName = path.basename(o.pages);
  mkdirSync(dir, { recursive: true });
  const wanted = new Map();
  for (const page of doc.pages) wanted.set(`${page.output ?? page.id}.html`, fill(template, viewOf(L, doc, page, dir, pagesName)));
  const problems = [];
  for (const [name, html] of wanted) {
    const file = path.join(dir, name), now = existsSync(file) ? read(file) : null;
    if (now === html) continue;
    if (o.check) problems.push(`${name}: ${now === null ? "missing" : "differs from the template and the page list"}`);
    else { writeFileSync(file, html); console.log(`wrote ${path.join(o.htmlOnly, name)}`); }
  }
  for (const name of readdirSync(dir).filter((n) => n.endsWith(".html") && !wanted.has(n)).sort()) {
    // only files this script wrote from the same page list: hand-written templates and other lists' files stay
    if (!read(path.join(dir, name)).includes(`from brand/og/template.html and ${pagesName}, page `)) continue;
    if (o.check) problems.push(`${name}: written by this script but no longer in the page list`);
    else { unlinkSync(path.join(dir, name)); console.log(`removed ${path.join(o.htmlOnly, name)} (not in the page list)`); }
  }
  for (const p of problems) console.log(`STALE ${p}`);
  console.log(o.check ? (problems.length ? `${problems.length} stale; run without --check` : `fresh: ${wanted.size} template(s) in ${o.htmlOnly}`)
                      : `${wanted.size} template(s) in ${o.htmlOnly}`);
  return problems.length ? 1 : 0;
}

// everything a page needs from the export, before anything is written (UsageError, exit 2)
function preflight(L, doc) {
  chevron(L);
  for (const page of doc.pages) {
    for (const id of [page.product ?? doc.site.product, ...(page.apps ?? [])]) tileOf(L, id, `page ${page.id}`);
  }
}

async function render(L, doc, o, template) {
  const { pw, version } = loadPlaywright();
  preflight(L, doc);
  const out = path.resolve(o.out), headDir = path.resolve(o.head ?? o.out);
  const made = o.keepHtml ? path.resolve(o.keepHtml) : mkdtempSync(path.join(tmpdir(), "sebaro-og-"));
  mkdirSync(out, { recursive: true }); mkdirSync(headDir, { recursive: true }); mkdirSync(made, { recursive: true });
  const work = realpathSync(made);       // the page's URL and its relative links on the same real path as ROOT
  const ranges = coverage(L), pagesName = path.basename(o.pages), words = WORDS[doc.site.lang ?? "de"];
  const fontsDir = pathToFileURL(path.dirname(L.fontsCss)).href + "/";
  const headJson = path.join(headDir, "head.json");
  if (existsSync(headJson)) unlinkSync(headJson);   // a run that stops early leaves none from an earlier run
  let browser;
  try {
    browser = await pw.chromium.launch({ headless: true, args: ["--force-color-profile=srgb", "--disable-lcd-text"] });
  } catch (e) {
    console.error(`error: Chromium did not start (npx playwright install --only-shell chromium): ${e.message.split("\n")[0]}`);
    return 1;
  }
  const failed = [], heads = [], chromium = browser.version();
  try {
    const context = await browser.newContext({ viewport: SIZE, deviceScaleFactor: 1, colorScheme: "light",
                                               reducedMotion: "reduce", locale: words.browser });
    let blocked = [], requests = [], consoleErrors = [];
    await context.route("**/*", (route) => {
      const url = route.request().url();
      if (LOCAL.test(url)) return route.continue();
      blocked.push(url);
      return route.abort("blockedbyclient");
    });
    const tab = await context.newPage();
    tab.on("request", (r) => requests.push(r.url()));
    tab.on("console", (m) => { if (m.type() === "error") consoleErrors.push(m.text()); });
    tab.on("pageerror", (e) => consoleErrors.push(String(e)));
    for (const page of doc.pages) {
      const name = page.output ?? page.id, png = path.join(out, `${name}.png`), problems = [];
      const snippet = path.join(headDir, `${name}.head.html`);
      const drop = () => { for (const f of [png, snippet]) if (existsSync(f)) unlinkSync(f); };  // stale or just written
      blocked = []; requests = []; consoleErrors = [];
      const view = viewOf(L, doc, page, work, pagesName);
      problems.push(...uncovered(ranges, view).map((c) => `sebaro Sans does not cover ${c}`));
      const file = path.join(work, `${name}.html`);
      writeFileSync(file, fill(template, view));
      await tab.goto(pathToFileURL(file).href, { waitUntil: "load", timeout: 60000 });
      const info = await tab.evaluate(judgeInPage, MAX_TITLE_LINES);
      problems.push(...info.problems);
      if (blocked.length) problems.push(`requests blocked: ${blocked.join(", ")}`);
      if (consoleErrors.length) problems.push(`console errors: ${consoleErrors.join(" | ").slice(0, 400)}`);
      const bad = info.fonts.filter((f) => f.status === "error").map((f) => `${f.family} ${f.style} ${f.weight}`);
      if (bad.length) problems.push(`fonts failed to load: ${bad.join(", ")}`);
      if (!info.fonts.some((f) => f.family === "sebaro Sans" && f.style === "normal" && f.status === "loaded")) {
        problems.push("sebaro Sans (upright) did not load (document.fonts)");
      }
      const outside = requests.filter((u) => /\.(woff2?|ttf|otf)(\?|$)/i.test(u) && !u.startsWith(fontsDir));
      if (outside.length) problems.push(`font files outside fonts/: ${outside.join(", ")}`);
      if (info.theme !== "light") problems.push(`template sets data-theme=${info.theme}, share images are light`);
      const want = parseColour(info.bg);
      if (!want) problems.push(`--sb-color-bg under data-theme="light" is ${JSON.stringify(info.bg)}, not a colour`);
      const shot = await tab.screenshot({ clip: { x: 0, y: 0, ...SIZE }, animations: "disabled", timeout: 60000 });
      const img = rgbOf(decodePng(shot));
      if (img.alphaMin < 255) problems.push("the screenshot has transparent pixels");
      if (problems.length) { failed.push([page.id, problems]); drop(); continue; }
      writeFileSync(png, encodePng(img));
      // the written file again: size, colour type, ground
      const back = decodePng(readFileSync(png)), g = ground(back), after = [];
      if (back.width !== SIZE.width || back.height !== SIZE.height) after.push(`${back.width} x ${back.height}, expected 1200 x 630`);
      if (back.colorType !== 2) after.push(`PNG colour type ${back.colorType}, expected 2 (RGB, no alpha)`);
      if (g.rgb.some((v, i) => Math.abs(v - want[i]) > GROUND_TOLERANCE)) {
        after.push(`ground ${hex(g.rgb)} (${Math.round(g.share * 100)} % of the pixels) is not color.bg light ${hex(want)}`);
      }
      if (after.length) { failed.push([page.id, after]); drop(); continue; }
      const product = page.product ?? doc.site.product;
      const head = headOf(doc, page, view.productName, view.apps.map((a) => a.name));
      writeFileSync(snippet, head.html);
      heads.push({ id: head.id, output: name, image: head.image, alt: head.alt, product, tags: head.tags });
      console.log(`ok   ${page.id} -> ${path.join(o.out, `${name}.png`)} (title ${info.lines} line(s), ground ${hex(g.rgb)})`);
    }
  } finally {
    await browser.close();
    if (!o.keepHtml) rmSync(work, { recursive: true, force: true });
  }
  writeFileSync(headJson, JSON.stringify({ $comment: `${MARK} ${VERSION} from ${pagesName}; do not edit`,
    width: SIZE.width, height: SIZE.height, pages: heads }, null, 2) + "\n");
  for (const [id, problems] of failed) console.log(`FAIL ${id}: ${problems.join("; ")}`);
  console.log(`${heads.length} / ${doc.pages.length} page(s) rendered (Playwright ${version ?? "?"}, Chromium ${chromium})` +
              (failed.length ? `; failed: ${failed.map(([id]) => id).join(", ")}` : ""));
  return failed.length ? 1 : 0;
}

export async function main(argv) {
  try {
    const o = args(argv);
    if (o.version) { console.log(`render.mjs ${VERSION}`); return 0; }
    const L = layout();
    const doc = loadPages(L, path.resolve(o.pages));
    const template = read(L.template);
    return o.htmlOnly ? htmlOnly(L, doc, o, template) : await render(L, doc, o, template);
  } catch (e) {
    if (e instanceof UsageError) { console.error(`error: ${e.message}`); return 2; }
    console.error(`error: ${e.stack || e}`);
    return 1;
  }
}

