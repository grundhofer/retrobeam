#!/usr/bin/env node
// sebaro share images (W6a, WEB-09; spec/09 §18.1; D96): one 1200 x 630 PNG per page from a page list, rendered in a
// website's own build from the one template of sebaroDesign (D96 (a)). Node 20+ and Playwright with Chromium (the
// build's choice; Chromium only, like the CI under D96 (b)); nothing else, no network.
//
//   node <sebaro>/brand/og/render.mjs --pages og-pages.json --out public/og [--head build/og-head] [--keep-html DIR]
//   node <sebaro>/brand/og/render.mjs --pages pages.json --html-only DIR [--check]     # the filled templates only
//   node <sebaro>/brand/og/render.mjs --version
//
// <sebaro> is the folder of a `export_system.py --target web` export (this file is brand/og/render.mjs in it) or, in
// sebaroDesign, systems/sebaro. Everything is found relative to this file: tokens.css (dist/tokens.css in the
// workshop), fonts/fonts.css with fonts/web/*.woff2, icons/sprite.svg + sprite.css (icons/dist/ in the workshop),
// brand/inline/tile-<id>.svg and lockup-horizontal(-large).svg, brand/og/template.html, brand/og/pages.schema.json.
//
// The page list (pages.schema.json, checked against that file by this script): site {product, name, origin, lang?,
// imageBase?} and pages [{id, url, title, path?, readingMinutes?, date?, dateKind?, product?, output?, description?,
// type?, alt?, apps?}]. Per page it writes <out>/<output>.png (24-bit RGB, no alpha, sRGB chunk, no other metadata)
// and into --head (default: --out) <output>.head.html, the head tags of spec/09 §18.1 (canonical, description,
// og:*, twitter:card), plus head.json with the same tags for every page as data. The site still writes <title>, the
// language alternates (spec/09 §18.2), serves the PNGs under site.origin + site.imageBase and includes the snippet.
//
// Every page is checked before its PNG is written, and the PNG again after it is written; any failure names the page
// id, writes no image for it (a stale one from an earlier run is removed) and the script exits 1 after the other pages;
// its stale <output>.head.html goes with it. Checks: a request that is not file:/data:/blob:/about: (blocked), a font
// face that failed to load or no loaded upright sebaro Sans face (document.fonts), a character sebaro Sans does not
// cover (its unicode-range in fonts.css; the browser would draw it in a fallback font), a title that needs more than
// three lines or a word wider than its column (never cut, never set smaller: mark break points with U+00AD), a crumb,
// name, meta or app row wider than its line, content outside 1200 x 630, and in the written file 1200 x 630, colour
// type 2 (RGB, no alpha) and the most frequent colour = color.bg light (--sb-color-bg under data-theme="light" from
// tokens.css, ±2 per channel, like brand_assets.py BA37), plus a console error in the page and a font file loaded from
// outside fonts/. Every export file and every page's tiles are found before anything is written, so exit 2 leaves the
// output as it was; head.json is removed before the browser starts and written at the end with the pages that passed.
// The same input gives the same bytes (same Chromium; test_og_render.py checks it). Right to left is not supported.
// Exit codes: 0 ok · 1 a page failed or the browser could not run · 2 usage or input error (bad page list, missing
// export file, no Playwright).
//
// Versions (CHANGELOG):
//   1.0.0  2026-10-23  first version (D96 (a)): template, page list 1.0, head tags, self-checks; the workshop's
//                      brand/src/og/*.html are written with --html-only from brand/src/og/*.pages.json.
//   1.0.1  2026-10-25  the meta line draws a host with umlauts as written („bücher.example“), not in its punycode
//                      form (URL.host gave „xn--bcher-kva.example“); the head tags keep the URL's ASCII form (OR-14).
