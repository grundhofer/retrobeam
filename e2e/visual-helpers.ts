import { expect, type Page } from "@playwright/test";

// The same join every board spec keeps a local copy of. Kept out of helpers.ts
// so the visual spec does not turn into a reason to touch the others.
export async function join(page: Page, name: string): Promise<void> {
  await page.getByRole("textbox").fill(name);
  await page.getByRole("button", { name: /^(join|beitreten)$/i }).click();
  await expect(page.getByTestId("roster-item").first()).toBeVisible();
}
